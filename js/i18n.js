class NayvoI18nEngine {
  constructor() {
    this.currentLanguage = localStorage.getItem('nayvo_lang') || 'en';
  }

  getLanguage() {
    return this.currentLanguage;
  }

  setLanguage(langCode) {
    if (NAYVO_DICTIONARY[langCode]) {
      this.currentLanguage = langCode;
      localStorage.setItem('nayvo_lang', langCode);
      document.documentElement.lang = langCode;
      this.applyTranslations();
      window.dispatchEvent(new CustomEvent('nayvo_lang_changed', { detail: { lang: langCode } }));
    }
  }

  t(key) {
    const dict = NAYVO_DICTIONARY[this.currentLanguage] || NAYVO_DICTIONARY.en;
    return dict[key] || NAYVO_DICTIONARY.en[key] || key;
  }

  formatViews(count) {
    if (count == null) return '0 views';
    if (count >= 10000000) return `${(count / 10000000).toFixed(1)} Cr views`;
    if (count >= 100000) return `${(count / 100000).toFixed(1)} Lakh views`;
    if (count >= 1000) return `${(count / 1000).toFixed(1)}K views`;
    return `${count} views`;
  }

  formatSubscribers(count) {
    if (count == null) return '0 subscribers';
    if (count >= 10000000) return `${(count / 10000000).toFixed(1)}M subscribers`;
    if (count >= 100000) return `${(count / 100000).toFixed(1)}L subscribers`;
    if (count >= 1000) return `${(count / 1000).toFixed(1)}K subscribers`;
    return `${count} subscribers`;
  }

  applyTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const text = this.t(key);
      if (text) el.textContent = text;
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      const text = this.t(key);
      if (text) el.setAttribute('placeholder', text);
    });

    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      const text = this.t(key);
      if (text) el.setAttribute('title', text);
    });
  }
}

window.NayvoI18n = new NayvoI18nEngine();
window.MayaviI18n = window.NayvoI18n; // Backward compatibility alias
